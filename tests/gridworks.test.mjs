// A budget-constrained construction plan exercises every campaign target using
// actual purchase/upgrade APIs. No credits, tiers, outputs, or objectives are injected.
function solveCity(index) {
  const s = createGame(index), level = LEVELS[index], cx = Math.floor(s.width / 2), cy = Math.floor(s.height / 2);
  if (index === 0) { put(s, cx - 1, cy + 1, 'coal'); put(s, cx, cy + 1, 'tower3g'); tick(s, 15); return s; }
  const tier = index === 1 || index === 2 ? 2 : 3;
  const type = index >= 12 ? 'tower5g' : index >= 6 ? 'tower4g' : 'tower3g';
  const towerTier = index >= 12 ? 1 : index >= 6 ? 2 : tier;
  for (let y = cy - 2; y <= cy + 1; y++) for (let x = cx - 5; x <= cx + 5; x++) {
    if (!s.cells.some(c => c.x === x && c.y === y && c.type === 'line')) put(s, x, y, 'line');
    const old = s.cells.find(c => c.x === x && c.y === y && BUILDINGS[c.type].layer === 'data');
    if (index >= 4 && old) demolish(s, old.id);
    if (!old || index >= 4) put(s, x, y, index >= 4 ? 'fiber' : 'cat6');
  }
  const dc = s.cells.find(c => c.type === 'datacenter');
  const dcTier = index >= 12 ? 3 : 2;
  while (dc.tier < dcTier) assert.ok(upgradeBuilding(s, dc.id).ok);
  if (index >= 3) {
    const hardwareTier = index >= 12 ? 3 : 2;
    for (const key of ['cpu', 'storage', ...(index >= 11 ? ['gpu', 'cooling'] : [])]) while (dc.modules[key] < hardwareTier) assert.ok(upgradeModule(s, dc.id, key).ok);
  }
  put(s, cx, cy + 1, type, towerTier);
  if (level.targets.tower5g === 2) { put(s, cx, cy + 2, 'line'); put(s, cx, cy + 2, 'fiber'); put(s, cx, cy + 2, 'tower5g'); }
  if (index >= 4) put(s, cx + 2, cy + 1, 'router');
  else if (index >= 2) put(s, cx + 2, cy + 1, 'switch');
  if (index >= 5 && index < 9) put(s, cx - 2, cy + 1, 'gas');
  else if (index >= 11) { put(s, cx - 2, cy + 1, 'nuclear'); put(s, cx + 3, cy + 1, 'substation'); }
  else if (index >= 3) {
    for (let i = 0; i < (index >= 9 ? 2 : 1); i++) {
      const y = cy + i, x = s.terrain[y * s.width + 4] === 'water' ? 5 : 4;
      put(s, x, y, 'hydro');
      for (let xx = x; xx < cx - 5; xx++) put(s, xx, y, 'line');
    }
    if (index < 9) put(s, cx - 2, cy + 1, 'wind');
  } else put(s, cx - 2, cy + 1, 'coal');
  for (let i = 0; i < (level.targets.battery || 0); i++) put(s, [cx - 5, cx + 5, cx + 1][i], cy + 1, 'battery');
  if (level.targets.gateway || index >= 13) put(s, cx - 3, cy + 1, 'gateway');
  if (level.targets.firewall) put(s, cx + 1, cy + 1, 'firewall');
  if (index >= 10) put(s, cx - 1, cy + 1, 'leo', index >= 15 ? 3 : 1);
  for (const key of ['maintenance', 'operator', 'planner'].slice(0, level.targets.automations || 0)) assert.ok(buyAutomation(s, key).ok);
  const neededHomes = Math.max(4, Math.ceil(level.targets.residents / (tier === 2 ? 20 : 35)));
  for (const home of s.cells.filter(c => c.type === 'home')) while (home.tier < tier) assert.ok(upgradeBuilding(s, home.id).ok);
  const slots = [];
  for (const y of [cy - 1, cy - 2, cy]) for (let x = cx - 5; x <= cx + 5; x++) if (!s.cells.some(c => c.x === x && c.y === y && BUILDINGS[c.type].layer === 'building')) slots.push([x, y]);
  let homes = 4;
  while (homes++ < neededHomes) { const [x, y] = slots.shift(); put(s, x, y, 'home', tier); }
  for (let i = 0; i < (level.targets.businesses || 0); i++) { const [x, y] = slots.shift(); put(s, x, y, 'business'); }
  if (analyze(s).power.deficit > 1 && !s.cells.some(c => c.type === 'substation')) put(s, cx + 3, cy + 1, 'substation');
  assert.ok(s.credits >= 0, `${level.name}: construction exceeds budget`);
  tick(s, 25);
  return s;
}

test('all eighteen fictional campaign cities are solvable within their construction budgets', () => {
  assert.ok(LEVELS.length >= 15);
  for (let index = 0; index < LEVELS.length; index++) {
    const s = solveCity(index);
    assert.equal(s.missionComplete, true, `${LEVELS[index].name}: ${JSON.stringify(getObjectives(s).filter(o => !o.complete))}; credits=${Math.round(s.credits)}`);
  }
});

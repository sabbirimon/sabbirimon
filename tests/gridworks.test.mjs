import test from 'node:test';
import assert from 'node:assert/strict';
import { BUILDINGS, LEVELS, createGame, placeBuilding, upgradeBuilding, demolish, repair, analyze, tick, getObjectives, serialize, restoreGame, upgradeModule, buyAutomation, configureAutomation, setServicePrice } from '../docs/gridworks/engine.js';

function put(s, x, y, type, tier = 1) {
  const r = placeBuilding(s, x, y, type); assert.equal(r.ok, true, `${type} at ${x},${y}: ${r.message}`);
  while (r.cell.tier < tier) assert.equal(upgradeBuilding(s, r.id).ok, true, `Upgrade ${type}`);
  return r.cell;
}
function blank() { const s = createGame(17, { sandbox: true }); s.cells = []; s.nextId = 1; return s; }
function basic() {
  const s = blank(); const plant = put(s, 10, 10, 'coal'); const dc = put(s, 11, 10, 'datacenter');
  const tower = put(s, 12, 10, 'tower3g'); const home = put(s, 13, 10, 'home');
  return { s, plant, dc, tower, home };
}

test('starter city has no instant service income; affordable first actions complete its mission', () => {
  const s = createGame(); assert.equal(analyze(s).income, 0);
  put(s, 13, 11, 'coal'); put(s, 14, 11, 'tower3g');
  assert.equal(analyze(s).service, 100); assert.ok(analyze(s).net > 0);
  assert.equal(tick(s, 15).completed, true); assert.equal(s.missionComplete, true);
  assert.ok(getObjectives(s).every(o => o.complete)); assert.ok(s.credits > 1000);
});

test('power, data and building layers coexist; duplicate layers and unaffordable builds do not mutate the city', () => {
  const s = blank(); put(s, 10, 10, 'line'); put(s, 10, 10, 'fiber'); put(s, 10, 10, 'home');
  const before = serialize(s);
  assert.equal(placeBuilding(s, 10, 10, 'cat6').ok, false); assert.equal(serialize(s), before);
  s.credits = 0; assert.equal(placeBuilding(s, 11, 10, 'nuclear').ok, false);
  assert.equal(s.cells.length, 3); assert.equal(placeBuilding(s, -1, 0, 'line').ok, false);
  assert.equal(placeBuilding(createGame(), 7, 7, 'nuclear').ok, false);
});

test('electricity and data use separate continuous networks', () => {
  const s = blank(); put(s, 8, 10, 'coal'); const dc = put(s, 12, 10, 'datacenter');
  const tower = put(s, 16, 10, 'tower3g'); put(s, 16, 11, 'home');
  for (let x = 8; x <= 16; x++) put(s, x, 10, 'line');
  for (let x = 12; x <= 16; x++) put(s, x, 10, 'cat6');
  assert.equal(analyze(s).service, 100);
  const cable = s.cells.find(c => c.type === 'cat6' && c.x === 14); demolish(s, cable.id);
  assert.equal(analyze(s).buildings[tower.id].powered, true); assert.equal(analyze(s).service, 0);
  put(s, 14, 10, 'cat6'); dc.health = 0;
  assert.equal(analyze(s).buildings[tower.id].dataConnected, false);
});

test('Cat6 distance limits are regenerated by a powered switch', () => {
  const s = blank(); put(s, 8, 6, 'coal'); put(s, 9, 6, 'datacenter'); const tower = put(s, 24, 6, 'tower3g'); put(s, 24, 7, 'home');
  for (let x = 8; x <= 24; x++) put(s, x, 6, 'line');
  for (let x = 10; x <= 24; x++) put(s, x, 6, 'cat6');
  assert.equal(analyze(s).buildings[tower.id].dataConnected, false);
  put(s, 17, 6, 'switch'); assert.equal(analyze(s).service, 100);
});

test('power deficits reduce delivered service; reserve generation restores it', () => {
  const s = blank(); put(s, 10, 10, 'solar'); put(s, 11, 10, 'datacenter'); put(s, 12, 10, 'tower3g');
  for (let x = 13; x <= 16; x++) put(s, x, 10, 'home');
  const low = analyze(s); assert.ok(low.power.deficit > 0); assert.ok(low.service < 100);
  const reserve = put(s, 10, 11, 'diesel');
  const restored = analyze(s); assert.equal(restored.service, 100); assert.ok(restored.buildings[reserve.id].output > 0);
  put(s, 9, 10, 'coal'); assert.equal(analyze(s).buildings[reserve.id].output, 0);
});

test('UPS storage charges with surplus and discharges through an outage', () => {
  const { s, plant } = basic(); const battery = put(s, 11, 11, 'battery');
  const initial = battery.energy; tick(s, 1); assert.ok(battery.energy > initial);
  plant.health = 0; const before = battery.energy;
  assert.equal(analyze(s).power.deficit, 0); tick(s, 1); assert.ok(battery.energy < before);
  battery.energy = 0; assert.ok(analyze(s).power.deficit > 0);
});

test('upgrades increase capacity and demand; cooling prevents hardware throttling', () => {
  const { s, dc } = basic();
  for (const key of ['cpu', 'gpu', 'storage']) { assert.ok(upgradeModule(s, dc.id, key).ok); assert.ok(upgradeModule(s, dc.id, key).ok); }
  const hot = analyze(s); assert.ok(hot.buildings[dc.id].thermalEfficiency < 1);
  upgradeModule(s, dc.id, 'cooling'); upgradeModule(s, dc.id, 'cooling');
  const cool = analyze(s); assert.equal(cool.buildings[dc.id].thermalEfficiency, 1); assert.ok(cool.compute > hot.compute);
  const previousDemand = cool.buildings[dc.id].demand; upgradeBuilding(s, dc.id);
  assert.ok(analyze(s).buildings[dc.id].demand > previousDemand);
});

test('repair restores condition, selling refunds only invested credits, and pricing trades adoption for price', () => {
  const { s, home } = basic(); home.health = 20;
  assert.ok(repair(s, home.id).ok); assert.equal(home.health, 100);
  const customers = analyze(s).customers; setServicePrice(s, 1.5); assert.ok(analyze(s).customers < customers);
  const before = s.credits; const sold = demolish(s, home.id);
  assert.ok(sold.refund > 0 && sold.refund < BUILDINGS.home.cost); assert.equal(s.credits, before + sold.refund);
});

test('LEO backhaul provides distant coverage and virtual regional connections', () => {
  const s = blank(); put(s, 10, 10, 'coal'); put(s, 11, 10, 'datacenter'); put(s, 12, 10, 'leo');
  for (let x = 12; x <= 27; x++) put(s, x, 10, 'line');
  put(s, 27, 11, 'home');
  const report = analyze(s); assert.equal(report.service, 100); assert.equal(report.satelliteCoverage, 100); assert.equal(report.regionalLinks, 3);
});

test('automation repairs actual assets and respects the reserve budget', () => {
  const { s, plant } = basic(); assert.ok(buyAutomation(s, 'maintenance').ok);
  plant.health = 20; configureAutomation(s, 'maintenance', { reserve: 100000 }); tick(s, 25); assert.equal(plant.health, 20);
  configureAutomation(s, 'maintenance', { reserve: 500 }); tick(s, 25); assert.equal(plant.health, 100); assert.ok(s.credits >= 500);
  assert.ok(s.events.some(event => event.title === 'Maintenance drone'));
});

test('fixed simulation steps and incidents are deterministic across frame sizes', () => {
  const a = createGame(4), b = restoreGame(serialize(a));
  for (let i = 0; i < 220; i++) tick(a, 1);
  for (let i = 0; i < 880; i++) tick(b, .25);
  assert.deepEqual(a, b); assert.ok(a.events.length > 1);
  assert.equal(a.cells.length, b.cells.length);
});

